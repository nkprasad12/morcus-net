/**
 * What's New: announces the newest `#release` post on the updates blog
 * (`https://updates.morcus.net/latest.json`) on the dictionary landing page.
 *
 * {@link LatestPostPoller} polls `latest.json`, validates it with
 * {@link parseLatestPost}, and exposes it while {@link isRecentPost} holds.
 * The landing page renders the `#whats-new` banner (`dict_landing.server.ts`)
 * and its pre-paint selector rule in `<head>` (`dict_page.server.ts`).
 * Server-only: the client just reads `data-wn-date` from the rendered HTML.
 */

import { envVar } from "@/common/env_vars";

/** Posts older than this are never announced, however long a user was away. */
export const WHATS_NEW_MAX_AGE_DAYS = 10;

/** Longer descriptions are cut, so a bad post can't fill the screen. */
const MAX_DESCRIPTION_LENGTH = 200;

const UPDATES_ORIGIN = "https://updates.morcus.net";
const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;
const DAY_MS = 24 * 60 * 60 * 1000;

/** The newest release post, as published in the blog's `latest.json`. */
export interface LatestPost {
  /** Publication date, `YYYY-MM-DD` (UTC). Also the post's identity. */
  readonly date: string;
  /** The post's one-line summary; absent if the post has none. */
  readonly description?: string;
  /** Absolute `https://updates.morcus.net/...` URL of the post. */
  readonly url: string;
}

/**
 * Checks that `value` is a real calendar date in `YYYY-MM-DD` format.
 *
 * Load-bearing security invariant: `post.date` is interpolated into an inline
 * `<style>` attribute selector in `dict_page.server.ts`, so this strict check
 * prevents CSS/HTML breakout.
 */
export function isValidIsoDate(value: string): boolean {
  if (!ISO_DATE.test(value)) return false;
  const parsed = new Date(`${value}T00:00:00Z`);
  // Rejects dates like 2026-02-31, which `Date` silently rolls over.
  return (
    !Number.isNaN(parsed.getTime()) &&
    parsed.toISOString().slice(0, 10) === value
  );
}

function parseUpdatesUrl(value: string): string | undefined {
  try {
    const url = new URL(value);
    return url.protocol === "https:" && url.origin === UPDATES_ORIGIN
      ? url.href
      : undefined;
  } catch {
    return undefined;
  }
}

function cleanDescription(value: unknown): string | undefined {
  if (typeof value !== "string") return undefined;
  const text = value.replace(/\s+/g, " ").trim();
  if (text.length === 0) return undefined;
  return text.length <= MAX_DESCRIPTION_LENGTH
    ? text
    : `${text.slice(0, MAX_DESCRIPTION_LENGTH - 1).trimEnd()}…`;
}

/**
 * Validates untrusted JSON as a {@link LatestPost}: a real `YYYY-MM-DD` date
 * and an `https://updates.morcus.net/` URL are required, and the description
 * is optional, whitespace-normalized and length-capped. Returns `undefined` if
 * invalid.
 */
export function parseLatestPost(raw: unknown): LatestPost | undefined {
  if (typeof raw !== "object" || raw === null) return undefined;
  if (!("date" in raw) || !("url" in raw)) return undefined;
  const { date, url } = raw;
  if (typeof date !== "string" || !isValidIsoDate(date)) return undefined;
  if (typeof url !== "string") return undefined;
  const href = parseUpdatesUrl(url);
  if (href === undefined) return undefined;
  const description = cleanDescription(
    "description" in raw ? raw.description : undefined
  );
  return description === undefined
    ? { date, url: href }
    : { date, description, url: href };
}

/**
 * Whether `post` has a non-empty description and was published within the
 * `[0, maxAgeDays]` window relative to `now` (`0 <= now - postDate <= maxAgeDays`).
 */
export function isRecentPost(
  post: LatestPost,
  now: Date = new Date(),
  maxAgeDays: number = WHATS_NEW_MAX_AGE_DAYS
): boolean {
  if (!post.description || !isValidIsoDate(post.date)) return false;
  const ageMs = now.getTime() - Date.parse(`${post.date}T00:00:00Z`);
  return ageMs >= 0 && ageMs <= maxAgeDays * DAY_MS;
}

/** The blog's newest release post, generated by Jekyll (`morcus-blog/latest.json`). */
export const DEFAULT_LATEST_POST_URL = "https://updates.morcus.net/latest.json";

const DEFAULT_REFRESH_MS = 60 * 60 * 1000;
const DEFAULT_TIMEOUT_MS = 10 * 1000;

/** Anything that knows the active release post to announce on the landing page. */
export interface LatestPostSource {
  /**
   * The newest valid release post within the 10-day announcement window
   * (with a non-empty description), or `null` if none is active.
   */
  current(now?: Date): LatestPost | null;
  /** Registers a listener invoked whenever a poll changes the active post. */
  onChange?(listener: (post: LatestPost | null) => void): void;
}

export interface LatestPostPollerOptions {
  /** Defaults to {@link DEFAULT_LATEST_POST_URL}. */
  url?: string;
  /** Defaults to hourly. */
  refreshMs?: number;
  /** Per-request timeout. Defaults to 10 s. */
  timeoutMs?: number;
  /** Injectable for tests. Defaults to the global `fetch`. */
  fetchFn?: typeof fetch;
  /** Injectable clock for tests. Defaults to `() => new Date()`. */
  now?: () => Date;
  /** Defaults to `console.warn`. */
  warn?: (message: string) => void;
  /** Invoked whenever the active post changes after a refresh. */
  onChange?: (post: LatestPost | null) => void;
}

/**
 * Polls the blog's `latest.json` and exposes the active release post when it
 * falls within the 10-day announcement window. A failed or invalid fetch keeps
 * the previous post, so a transient blog outage never drops an active
 * announcement or breaks the page.
 */
export class LatestPostPoller implements LatestPostSource {
  readonly #url: string;
  readonly #refreshMs: number;
  readonly #timeoutMs: number;
  readonly #fetch: typeof fetch;
  readonly #now: () => Date;
  readonly #warn: (message: string) => void;
  readonly #listeners = new Set<(post: LatestPost | null) => void>();
  #post: LatestPost | undefined = undefined;
  #lastNotifiedKey: string | null = null;
  #timer: ReturnType<typeof setInterval> | undefined = undefined;

  constructor(options: LatestPostPollerOptions = {}) {
    this.#url = options.url ?? DEFAULT_LATEST_POST_URL;
    this.#refreshMs = options.refreshMs ?? DEFAULT_REFRESH_MS;
    this.#timeoutMs = options.timeoutMs ?? DEFAULT_TIMEOUT_MS;
    this.#fetch = options.fetchFn ?? fetch;
    this.#now = options.now ?? (() => new Date());
    this.#warn = options.warn ?? ((message) => console.warn(message));
    if (options.onChange) {
      this.#listeners.add(options.onChange);
    }
  }

  /**
   * Returns the active post if one has been fetched, has a non-empty
   * description, and is within the 10-day window at `now`; otherwise `null`.
   */
  current(now: Date = this.#now()): LatestPost | null {
    const post = this.#post;
    if (post === undefined || !isRecentPost(post, now)) return null;
    return post;
  }

  onChange(listener: (post: LatestPost | null) => void): void {
    this.#listeners.add(listener);
  }

  /** Fetches now, then every `refreshMs`. The timer never keeps the process alive. */
  start(): void {
    if (this.#timer !== undefined) return;
    void this.refresh();
    this.#timer = setInterval(() => void this.refresh(), this.#refreshMs);
    this.#timer.unref();
  }

  stop(): void {
    clearInterval(this.#timer);
    this.#timer = undefined;
  }

  /** One fetch. Never rejects; failures are logged and keep the last post. */
  async refresh(): Promise<void> {
    try {
      const response = await this.#fetch(this.#url, {
        signal: AbortSignal.timeout(this.#timeoutMs),
      });
      if (!response.ok) {
        this.#warn(`What's New: ${this.#url} returned ${response.status}.`);
        return;
      }
      const post = parseLatestPost(await response.json());
      if (post === undefined) {
        this.#warn(`What's New: ${this.#url} returned an invalid post.`);
        return;
      }
      this.#post = post;
    } catch (err) {
      this.#warn(`What's New: fetching ${this.#url} failed: ${String(err)}`);
    } finally {
      this.#notifyIfChanged();
    }
  }

  #notifyIfChanged(): void {
    const active = this.current();
    const nextKey = active?.description
      ? `${active.date}\n${active.description}\n${active.url}`
      : null;
    if (nextKey === this.#lastNotifiedKey) return;
    this.#lastNotifiedKey = nextKey;
    for (const listener of this.#listeners) {
      try {
        listener(active);
      } catch (err) {
        this.#warn(`What's New: listener failed: ${String(err)}`);
      }
    }
  }
}

/**
 * Builds the {@link LatestPostPoller} selected by `LATEST_POST_URL`
 * (`DEFAULT_ENV_VARS` defaults to {@link DEFAULT_LATEST_POST_URL}).
 * Setting `LATEST_POST_URL` to `""` or `"off"` disables polling and returns
 * `undefined` (used by the local dev server and E2E / visual regression suites).
 */
export function latestPostFromEnv(
  env: NodeJS.ProcessEnv = process.env
): LatestPostPoller | undefined {
  const raw = env.LATEST_POST_URL;
  if (raw === "" || raw === "off") return undefined;
  const url = raw ?? envVar("LATEST_POST_URL", "unsafe");
  if (!url || url === "off") return undefined;
  return new LatestPostPoller({ url });
}
